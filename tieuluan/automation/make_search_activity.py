from diagram_job import Diagram
d=Diagram('03-search-activity','ACTIVITY_DIAGRAM','UC01 Search and select an available fashion variant')
d.node('s-start','InitialNode','',345,30,20,20)
d.node('s-input-merge','MergeNode','',330,80,50,50)
d.node('s-input','ActivityAction','Enter keyword and filters',225,165,260,60)
d.node('s-query','ActivityAction','Find published products\\nmatching variant filters',225,280,260,65)
d.node('s-found','DecisionNode','',330,400,50,50)
d.node('s-empty','ActivityAction','Show no matching results\\nand suggest changing filters',600,395,260,65)
d.node('s-view','ActivityAction','Show product details, images,\\nmaterial and size chart',225,510,260,65)
d.node('s-select-merge','MergeNode','',330,610,50,50)
d.node('s-select','ActivityAction','Choose exact size and colour',225,700,260,60)
d.node('s-available','DecisionNode','',330,815,50,50)
d.node('s-unavailable','ActivityAction','Explain selected SKU unavailable\\nand allow another selection',600,810,260,65)
d.node('s-add','ActivityAction','Add selected SKU and quantity\\nto cart without reserving stock',225,935,260,65)
d.node('s-end','ActivityFinalNode','',340,1070,30,30)
for i,a,b in [('1','s-start','s-input-merge'),('2','s-input','s-query'),('3','s-query','s-found'),('4','s-view','s-select-merge'),('5','s-select','s-available'),('6','s-add','s-end'),('13','s-input-merge','s-input'),('14','s-select-merge','s-select')]:d.rel(i,'ControlFlow',a,b)
d.rel('7','ControlFlow','s-found','s-view',guard='matches exist')
d.rel('8','ControlFlow','s-found','s-empty',guard='no matches')
d.rel('9','ControlFlow','s-empty','s-input-merge',points='730,395;730,105;380,105')
d.rel('10','ControlFlow','s-available','s-add',guard='available > 0')
d.rel('11','ControlFlow','s-available','s-unavailable',guard='available = 0')
d.rel('12','ControlFlow','s-unavailable','s-select-merge',points='730,810;730,635;380,635')
for r in d.rows[1:]:
    if r[0]=='N':r[5]=round(r[5]*.60)+(30 if r[5]>=510 else 0)+(30 if r[5]>=935 else 0);r[7]=round(r[7]*.75)
    elif r[0]=='R' and r[9]:r[9]=';'.join(f'{x},{round(int(y)*.60)+(30 if int(y)>=510 else 0)+(30 if int(y)>=935 else 0)}' for x,y in (p.split(',') for p in r[9].split(';')))
d.save(True)
