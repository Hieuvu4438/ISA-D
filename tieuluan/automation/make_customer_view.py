from pathlib import Path
rows=[['01-customer-use-cases','USE_CASE_DIAGRAM','Customer services and payment boundary']]
def node(key,typ,name,x,y,w,h):rows.append(['N',key,typ,name,x,y,w,h])
def rel(key,typ,a,b,name='',points=''):rows.append(['R',key,typ,a,b,name,'','','',points])
node('customer_boundary','System','Atelier Fashion Ecommerce',240,30,690,900)
node('visitor','Actor','Visitor',60,85,80,100)
node('customer','Actor','Customer',60,430,80,100)
node('payment','Actor','Payment Provider',990,550,120,100)
for k,n,y in [('browse','UC01 Browse fashion catalogue',90),('account','UC02 Manage account',210),('cart','UC03 Manage variant cart',330),('checkout','UC04 Place order',450),('track','UC06 Track order',570),('cancel','UC07 Cancel order',690),('return','UC08 Request return or exchange',810)]:
    node(k,'UseCase',n,300,y,260,65)
node('validate','UseCase','Validate checkout',650,330,220,65)
node('reserve','UseCase','Reserve SKU stock',650,450,220,65)
node('initpay','UseCase','Initiate online payment',650,570,220,65)
node('payevent','UseCase','UC05 Reconcile payment event',650,740,250,65)
rel('inherit','Generalization','visitor','customer')
rel('browse-assoc','Association','visitor','browse')
for k in ['account','cart','checkout','track','cancel','return']:rel('customer-'+k,'Association','customer',k)
rel('include-validate','Include','checkout','validate',points='550,465;660,365')
rel('include-reserve','Include','checkout','reserve',points='560,482;650,482')
rel('include-initpay','Include','checkout','initpay',points='550,500;660,590')
rel('provider-payment','Association','payment','initpay')
rel('provider-event','Association','payment','payevent')
p=Path('automation/customer-view.tsv');p.write_text('\n'.join('\t'.join(map(str,r)) for r in rows),encoding='utf-8')
Path('automation/job.tsv').write_bytes(p.read_bytes())
